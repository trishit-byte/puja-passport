import { chromium } from '@playwright/test';
const b = await chromium.launch({ headless: true, args: process.env.CHROME_GPU_ARGS.split(' '), ignoreDefaultArgs: ['--enable-unsafe-swiftshader'] });
const p = await (await b.newContext({ viewport: { width: 1000, height: 700 } })).newPage();
await p.addInitScript(() => localStorage.setItem('anandapur.save', JSON.stringify({ tutorialDone: true })));
await p.goto('http://10.128.146.164:5174/?debug=1&autostart=1');
await p.waitForFunction(() => window.__game?.phase === 'play', null, { timeout: 90000 });
const [x, z, cx, cy, cz] = JSON.parse(process.argv[2]);
await p.evaluate(([x, z, cx, cy, cz]) => { const g = window.__game; window.__anandapur.teleport(x, z, 0); const pos = g.player.pos.clone(); pos.x += cx; pos.y = cy; pos.z += cz; const look = g.player.pos.clone(); g.cam.override = { pos, look }; document.querySelector('#ui').style.visibility = 'hidden'; }, [x, z, cx, cy, cz]);
await p.waitForTimeout(1500);
await p.screenshot({ path: 'docs/screenshots/dev/aerial.png' });
await b.close();
