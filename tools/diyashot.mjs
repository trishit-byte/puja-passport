import { chromium } from '@playwright/test';
const b = await chromium.launch({ headless: true, args: process.env.CHROME_GPU_ARGS.split(' '), ignoreDefaultArgs: ['--enable-unsafe-swiftshader'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 900 } });
await ctx.addInitScript(() => localStorage.setItem('anandapur.save', JSON.stringify({ tutorialDone: true })));
const p = await ctx.newPage();
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://10.128.146.164:5173/?debug=1&autostart=1');
await p.waitForFunction(() => window.__game?.phase === 'play', null, { timeout: 90000 });
const t = await p.evaluate(() => window.__anandapur.targets().find((x) => x.id === 'nodir-alo').targets);
const take = t.find((x) => x.id === 'lamp-take');
await p.evaluate(([x, z]) => window.__anandapur.teleport(x, z, Math.PI), [take.x, take.z]);
await p.waitForTimeout(500);
await p.keyboard.press('KeyE');
await p.waitForTimeout(800);
await p.evaluate(([x, z]) => { window.__anandapur.teleport(x, z + 3, 0); const c = window.__game.cam; c.yaw = Math.PI * 0.75; c.targetDistance = 2.6; c.pitch = 0.05; }, [take.x, take.z]);
await p.waitForTimeout(1500);
await p.screenshot({ path: 'docs/screenshots/dev/diya.png', clip: { x: 450, y: 200, width: 700, height: 650 } });
console.log('diya visible', await p.evaluate(() => window.__game['diya'].visible), errs.join('\n') || 'no errors');
await b.close();
