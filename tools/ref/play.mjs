import { chromium } from '@playwright/test';
const shots = process.argv[2];
const b = await chromium.connectOverCDP('http://127.0.0.1:9222');
const p = b.contexts()[0].pages()[0];
const snap = async n => { await p.screenshot({ path: `${shots}/${n}.png` }); console.log('shot', n); };
const ui = async () => console.log((await p.evaluate(() => document.body.innerText)).replace(/\s+/g,' ').slice(0,400));
await snap('01-loaded'); await ui();
await p.waitForTimeout(8000); await snap('02-after8s'); await ui();
const buttons = await p.evaluate(() => [...document.querySelectorAll('button,[role=button],a')].map(e => e.innerText.trim()).filter(Boolean));
console.log('buttons', buttons);
await p.mouse.click(800, 450); await p.waitForTimeout(3000); await snap('03-click'); await ui();
await p.keyboard.press('Enter'); await p.waitForTimeout(3000); await snap('04-enter'); await ui();
for (const k of ['KeyW','KeyD','KeyS','KeyA']) { await p.keyboard.down(k); await p.waitForTimeout(1500); await p.keyboard.up(k); await snap('05-move-'+k); }
await p.keyboard.down('ShiftLeft'); await p.keyboard.down('KeyW'); await p.waitForTimeout(2000); await p.keyboard.up('KeyW'); await p.keyboard.up('ShiftLeft'); await snap('06-shift-run');
await p.mouse.move(800,450); await p.mouse.down(); for (let i=0;i<20;i++){ await p.mouse.move(800+i*15,450-i*4); await p.waitForTimeout(30);} await p.mouse.up(); await p.waitForTimeout(600); await snap('07-orbit');
await p.mouse.wheel(0, 600); await p.waitForTimeout(800); await snap('08-wheel');
await p.keyboard.press('Space'); await p.waitForTimeout(400); await snap('09-space');
await p.keyboard.press('KeyE'); await p.waitForTimeout(1200); await snap('10-E'); await ui();
await p.keyboard.press('Escape'); await p.waitForTimeout(1200); await snap('11-esc'); await ui();
const perf = await p.evaluate(() => new Promise(r => { let n=0; const t0=performance.now(); const f=()=>{ n++; if(performance.now()-t0<3000) requestAnimationFrame(f); else r(n/3);}; requestAnimationFrame(f); }));
console.log('rAF fps ~', perf);
await p.setViewportSize({ width: 420, height: 860 }); await p.waitForTimeout(1500); await snap('12-narrow'); await p.setViewportSize({ width: 1600, height: 900 });
await b.close().catch(()=>{});
