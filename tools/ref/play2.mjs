import { chromium } from '@playwright/test';
const shots = process.argv[2];
const b = await chromium.connectOverCDP('http://127.0.0.1:9222');
const p = b.contexts()[0].pages()[0];
await p.setViewportSize({ width: 1600, height: 900 });
const snap = async n => { await p.screenshot({ path: `${shots}/${n}.png` }); console.log('shot', n); };
const ui = async (t) => console.log(t, JSON.stringify((await p.evaluate(() => document.body.innerText)).replace(/\s+/g,' ').slice(0,300)));
await p.mouse.click(800, 780); await p.waitForTimeout(1500); await snap('20-begin-1.5s'); await ui('after begin');
await p.waitForTimeout(5000); await snap('21-begin-6s'); await ui('6s');
await p.waitForTimeout(6000); await snap('22-begin-12s'); await ui('12s');
await p.mouse.click(800, 450); await p.waitForTimeout(2000); await snap('23-click'); await ui('click');
await p.keyboard.press('Space'); await p.waitForTimeout(1500); await snap('24-space'); await ui('space');
await p.keyboard.press('Enter'); await p.waitForTimeout(1500); await snap('25-enter'); await ui('enter');
for (const k of ['KeyW','KeyD','KeyS','KeyA']) { await p.keyboard.down(k); await p.waitForTimeout(1800); await p.keyboard.up(k); await snap('26-move-'+k); }
await p.keyboard.down('ShiftLeft'); await p.keyboard.down('KeyW'); await p.waitForTimeout(2500); await p.keyboard.up('KeyW'); await p.keyboard.up('ShiftLeft'); await snap('27-shift');
await p.mouse.move(800,450); await p.mouse.down(); for (let i=0;i<25;i++){ await p.mouse.move(800+i*16,450-i*5); await p.waitForTimeout(30);} await p.mouse.up(); await p.waitForTimeout(800); await snap('28-orbit');
await p.mouse.wheel(0, -800); await p.waitForTimeout(800); await snap('29-wheel-in');
await p.mouse.wheel(0, 1600); await p.waitForTimeout(800); await snap('30-wheel-out');
await p.keyboard.press('KeyE'); await p.waitForTimeout(1200); await snap('31-E'); await ui('E');
await p.keyboard.press('Escape'); await p.waitForTimeout(1200); await snap('32-esc'); await ui('esc');
await b.close().catch(()=>{});
