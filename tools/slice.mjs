import { chromium } from '@playwright/test';
const out = process.argv[2] || 'docs/screenshots/dev';
const b = await chromium.launch({ headless: true, args: process.env.CHROME_GPU_ARGS.split(' '), ignoreDefaultArgs: ['--enable-unsafe-swiftshader', '--mute-audio'] });
const p = await b.newPage({ viewport: { width: 1600, height: 900 } });
const logs = [];
p.on('console', (m) => { if (['error', 'warning'].includes(m.type())) logs.push(m.type() + ': ' + m.text().slice(0, 300)); });
p.on('pageerror', (e) => logs.push('pageerror: ' + e.message + '\n' + (e.stack||'').slice(0,500)));
const t0 = Date.now();
await p.goto('http://10.128.146.164:5174/?debug=1', { waitUntil: 'load' });
await p.waitForFunction(() => document.querySelector('.title-screen'), null, { timeout: 60000 });
console.log('title after ms', Date.now() - t0);
await p.waitForTimeout(2500);
await p.screenshot({ path: `${out}/s1-title.png` });
await p.click('.title-screen [data-a=start]');
await p.waitForTimeout(4500);
await p.screenshot({ path: `${out}/s2-after-intro.png` });
const api = (fn, ...a) => p.evaluate(([fn, a]) => window.__anandapur[fn](...a), [fn, a]);
console.log(JSON.stringify(await api('getState')));
await p.click('.tutorial [data-a=skip]').catch(() => console.log('no tutorial'));
await api('teleportTo', 'bonedi-bari', false);
await p.waitForTimeout(2500);
await p.screenshot({ path: `${out}/s3-bonedi-gate.png` });
await p.keyboard.down('KeyW'); await p.waitForTimeout(1800); await p.keyboard.up('KeyW');
await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/s4-bonedi-inside.png` });
await api('teleportTo', 'bonedi-bari', true);
await p.waitForTimeout(1500);
console.log('state', JSON.stringify(await api('getState')));
await p.screenshot({ path: `${out}/s5-bell-prompt.png` });
await p.keyboard.press('KeyE');
await p.waitForTimeout(900);
await p.screenshot({ path: `${out}/s6-stamp.png` });
await p.waitForTimeout(3500);
console.log('state', JSON.stringify(await api('getState')));
await p.keyboard.press('KeyP');
await p.waitForTimeout(900);
await p.screenshot({ path: `${out}/s7-passport.png` });
await p.keyboard.press('KeyP');
await p.keyboard.press('KeyM');
await p.waitForTimeout(700);
await p.screenshot({ path: `${out}/s8-map.png` });
await p.keyboard.press('KeyM');
console.log('render', JSON.stringify(await api('renderInfo')), JSON.stringify(await api('frameStats')));
console.log(logs.slice(0, 20).join('\n'));
await b.close();
